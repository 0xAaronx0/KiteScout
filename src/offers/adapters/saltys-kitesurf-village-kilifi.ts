// --- Sirvoy engine (live availability) --------------------------------------------------------
export interface SkvSample {
  checkIn: string; checkOut: string;
  /** the engine answered with a notice instead of room types: translation key + its words */
  notice: { key: string; text: string } | null;
  currency: string | null; types: KbiRoomType[]; cards: KbiRoomCard[];
}

function addDays(isoDate: string, n: number): string {
  const d = new Date(`${isoDate}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}
function daysIn(y: number, m: number): number { return new Date(Date.UTC(y, m, 0)).getUTCDate(); }

/** One 7-night stay per month for 12 months: arrival on the 2nd Saturday, or the first Saturday from tomorrow in the current month. */
export function skvSampleStays(today: string): Array<{ checkIn: string; checkOut: string }> {
  const y = Number(today.slice(0, 4)); const m = Number(today.slice(5, 7));
  const tomorrow = addDays(today, 1);
  const out: Array<{ checkIn: string; checkOut: string }> = [];
  for (let k = 0; k < MONTHS; k++) {
    const mm = ((m - 1 + k) % 12) + 1; const yy = y + Math.floor((m - 1 + k) / 12);
    const first = new Date(Date.UTC(yy, mm - 1, 1)).getUTCDay();
    let checkIn = iso(yy, mm, 1 + ((6 - first + 7) % 7) + 7);
    if (checkIn < tomorrow) {
      const dow = new Date(`${tomorrow}T00:00:00Z`).getUTCDay();
      checkIn = addDays(tomorrow, (6 - dow + 7) % 7);
    }
    if (checkIn.slice(0, 7) !== iso(yy, mm, 1).slice(0, 7)) continue;
    out.push({ checkIn, checkOut: addDays(checkIn, NIGHTS) });
  }
  return out;
}

/** Body the Sirvoy widget posts for the stay.at site (its script tag's data attributes + the search dates). */
export function skvWidgetBody(checkIn: string, checkOut: string): string {
  return JSON.stringify({
    container_id: 'sbw_widget_1', widget: 'normal', source: null, context: 'default', guest_id: null, copy_booking_id: null,
    form_id: SKV_FORM_ID, adults: String(ADULTS), check_in: checkIn, check_out: checkOut, target: 'results',
    host_page_url: `${BOOKING_URL}/`, wp_plugin_version: 'legacy',
  });
}

/** Widget answer -> results page URL (engine session id `t`). */
export function skvResultsUrl(widgetJson: string): string | null {
  const d = JSON.parse(widgetJson) as { status?: string; t?: string; html?: string };
  if (d.status !== 'ok') return null;
  const src = d.html?.match(/src="([^"]+)"/)?.[1];
  if (src) return src.replace(/&amp;/g, '&');
  return d.t ? `${SIRVOY}/engine/book_results?t=${d.t}&id=${SKV_FORM_ID}&container_id=sbw_widget_1` : null;
}

/** Results page -> room types / cards / currency, or the engine's notice ("No selection available ..."). */
export function parseSkvResults(html: string): Omit<SkvSample, 'checkIn' | 'checkOut'> {
  if (!/data-room-type-data=/.test(html)) {
    const m = html.match(ENGINE_NOTICE_RE);
    if (!m) throw new Error('saltys: Sirvoy results page has neither room types nor an engine notice');
    return { notice: { key: m[1], text: clean(m[2]) }, currency: null, types: [], cards: [] };
  }
  return { notice: null, ...parseKbiResults(html) };
}

const occOf = (t: KbiRoomType): number => (t.rates[ADULTS] ? ADULTS : Math.max(...Object.keys(t.rates).map(Number)));
const money = (n: number): string => (Number.isInteger(n) ? String(n) : n.toFixed(2));
/** nightly rate for 2 guests, rounded to cents (the engine averages a stay across rate changes: 99.37571) */
const rateOf = (t: KbiRoomType): number => Math.round(t.rates[occOf(t)] * 100) / 100;

/** Month bands per Sirvoy room type (merged where price and availability repeat). */
export function buildSkvEngineSlots(samples: SkvSample[], today: string): Slot[] {
  const names: string[] = [];
  for (const s of samples) for (const t of s.types) if (!names.includes(t.name)) names.push(t.name);
  const out: Slot[] = [];
  for (const name of names) {
    // inSample: the day is one of the sample's nights; a refused sample (engine notice) only speaks for its own nights
    type Day = { date: string; sample: SkvSample; type: KbiRoomType | null; inSample: boolean };
    const days: Day[] = [];
    for (const s of samples) {
      const y = Number(s.checkIn.slice(0, 4)); const m = Number(s.checkIn.slice(5, 7));
      const t = s.types.find(x => x.name === name) ?? null;
      // an open sample stands for its calendar month, from today on
      for (let d = 1; d <= daysIn(y, m); d++) {
        const date = iso(y, m, d);
        if (date >= today) days.push({ date, sample: s, type: t, inSample: date >= s.checkIn && date < s.checkOut });
      }
    }
    const cls = (d: Day): Availability => (d.sample.notice ? (!d.inSample ? 'unknown' : /^not_enough_beds/.test(d.sample.notice.key) ? 'sold_out' : 'closed')
      : !d.type || !Object.keys(d.type.rates).length ? 'unknown'
        : d.type.freeUnits === 0 ? 'sold_out' : d.type.freeUnits <= 2 ? 'limited' : 'available');
    const state = (d: Day) => `${cls(d)}|${d.sample.notice ? (d.inSample ? 'n' : 'x') : ''}|${d.type && Object.keys(d.type.rates).length ? rateOf(d.type) : '-'}`;
    for (const run of runsOf(days, state)) {
      const { sample, type: t, inSample } = run.first;
      const a = cls(run.first);
      const priced = !!t && Object.keys(t.rates).length > 0 && !sample.notice;
      const stay = `${sample.checkIn}..${sample.checkOut}`;
      out.push({
        key: `${keyPart(name)}|${run.start}`,
        startDate: run.start,
        endDate: run.end,
        unit: name,
        price: priced ? rateOf(t!) : null,
        currency: priced ? sample.currency : null,
        priceUnit: priced ? 'per_night' : null,
        priceBasis: 'room',
        occupancy: priced ? occOf(t!) : null,
        availability: a,
        availabilityText: sample.notice
          ? (inSample ? `Sirvoy: "${sample.notice.text}" (sample stay ${stay}, ${ADULTS} adults)`
            : `not sampled; the month's sample stay ${stay} was not bookable for ${ADULTS} adults (Sirvoy)`)
          : a === 'unknown' ? `not offered for the sample stay ${stay} (booked or not bookable for ${ADULTS} guests)`
            : `${t!.freeUnits} unit(s) free for the sample stay ${stay}, ${sample.currency} ${money(rateOf(t!))} per night (Sirvoy)`,
        spotsLeft: a === 'limited' ? t!.freeUnits : null,
      });
    }
  }
  return out;
}

export async function fetchSkvSample(checkIn: string, checkOut: string): Promise<SkvSample> {
  const widget = await fetchText(SKV_WIDGET_URL, { method: 'POST', body: skvWidgetBody(checkIn, checkOut), contentType: 'application/json', accept: 'application/json' });
  const url = skvResultsUrl(widget);
  if (!url) throw new Error(`saltys: Sirvoy widget answered without an engine session (${widget.slice(0, 120)})`);
  return { checkIn, checkOut, ...parseSkvResults(await fetchText(url, { accept: 'text/html' })) };
}

/** Engine slots; the printed room cards stay the slots when no sample returns a priced room type. */
export async function fetchSkvSlots(ctx: FetchContext, today: string): Promise<Slot[]> {
  const samples: SkvSample[] = [];
  for (const s of skvSampleStays(today)) {
    try { samples.push(await fetchSkvSample(s.checkIn, s.checkOut)); }
    catch (e) { ctx.incomplete(`Sirvoy sample ${s.checkIn}..${s.checkOut}: ${(e as Error).message}`); }
  }
  if (samples.some(s => s.types.some(t => Object.keys(t.rates).length > 0))) return buildSkvEngineSlots(samples, today);
  ctx.note(`saltys: Sirvoy gave no priced room type in ${samples.length} sample(s); slots from the printed room cards`);
  const rooms = parseSkvRooms(await fetchText(SKV_ROOMS_URL, { accept: 'text/html' }));
  if (rooms.length < 4) throw new Error(`saltys: room price cards not found or changed (${rooms.length} rooms with prices)`);
  return buildSkvSlots(rooms);
}

