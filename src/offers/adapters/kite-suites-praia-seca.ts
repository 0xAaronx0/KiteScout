import { fetchText } from '../http.js';
import { collapse, findPrices, parse } from '../parse.js';
import type { ContentRoom, OfferAdapter, OfferContent, Slot } from '../types.js';

const SITE = 'https://kitesuites.com.br';
export const KS_HOME_URL = `${SITE}/`;
export const KS_ROOMS_URL = `${SITE}/acomodacoes`;
export const KS_SERVICES_URL = `${SITE}/servicos`;
const WHATSAPP = '+5522999886066';

// --- local helpers ----------------------------------------------------------------------------
const memo = new Map<string, { at: number; p: Promise<string> }>();
/** one fetch per page per 10 minutes: fetchContent + fetchSlots in the same run share it */
function page(url: string): Promise<string> {
  const hit = memo.get(url);
  if (hit && Date.now() - hit.at < 10 * 60_000) return hit.p;
  const p = fetchText(url, { accept: 'text/html' });
  memo.set(url, { at: Date.now(), p });
  p.catch(() => memo.delete(url));
  return p;
}

/** visible text lines (head, scripts, styles and the site-builder chrome dropped) */
function lines(html: string): string[] {
  const root = parse(html);
  for (const el of root.querySelectorAll('head, script, style, noscript, svg, nav, header, footer')) el.remove();
  return root.structuredText.split('\n').map(l => collapse(l)).filter(l => l && !/^<!DOCTYPE/i.test(l));
}
const textOf = (html: string): string => lines(html).join(' ');

/** photo URL of a site-builder image (lazy owl-carousel data-src first) */
function imgUrl(img: { getAttribute(n: string): string | undefined }): string | null {
  const u = img.getAttribute('data-src') || img.getAttribute('src') || '';
  return /^https:\/\/yata-apix-[\w-]+\.s3-object\.locaweb\.com\.br\/[0-9a-f]{32}\.jpe?g$/i.test(u) ? u : null;
}

// --- pure parsers -----------------------------------------------------------------------------
export interface KsRoom {
  name: string;
  text: string;
  sizeM2: number | null;
  maxGuests: number | null;
  beds: string | null;
  amenities: string[];
  images: string[];
}

const AMENITY_EN: Array<[RegExp, string]> = [
  [/caf[ée] da manh[ãa]/i, 'Breakfast'], [/frigobar/i, 'Minibar'], [/ar-condicionado/i, 'Air conditioning'],
  [/\btv\b/i, 'TV'], [/wi-?fi/i, 'Wi-Fi'],
];

/** /acomodacoes: one cs-section per suite with its gallery and a text box (h3 name ... "Acomoda até n pessoas"). */
export function parseKsRooms(roomsHtml: string): KsRoom[] {
  const out: KsRoom[] = [];
  for (const sec of parse(roomsHtml).querySelectorAll('section.cs-section')) {
    const h3 = sec.querySelectorAll('.text-editor h3').map(h => collapse(h.text)).find(t => /^Suite\b/i.test(t));
    if (!h3) continue;
    const box = sec.querySelectorAll('.text-editor').find(e => collapse(e.querySelector('h3')?.text ?? '') === h3)!;
    const paras = box.querySelectorAll('p').map(p => collapse(p.text)).filter(Boolean);
    const text = paras.join(' ');
    const detailsIdx = paras.findIndex(p => /^DETALHES$/i.test(p));
    const details = detailsIdx >= 0 ? paras[detailsIdx + 1] ?? '' : '';
    const guests = Number(text.match(/(?:Acomoda|Acamoda)\s+até\s+(\d+)\s+pessoas/i)?.[1]) || null;
    let beds: string | null = null;
    if (/1 Cama Queen ou 2 de solteiro, mais 1 de solteiro/i.test(text)) beds = 'queen bed or two single beds, plus one single bed';
    else if (/cama de cas(?:u)?al e um beliche/i.test(text)) beds = 'double bed + bunk bed'; // printed "cama de casual"
    out.push({
      name: h3,
      text,
      sizeM2: Number(text.match(/(\d+)\s?m²/)?.[1]) || null,
      maxGuests: guests,
      beds,
      amenities: AMENITY_EN.filter(([re]) => re.test(details)).map(([, en]) => en),
      images: [...new Set(sec.querySelectorAll('img').map(imgUrl).filter((u): u is string => !!u))],
    });
  }
  return out;
}

function roomDescription(r: KsRoom): string {
  return [
    r.sizeM2 ? `${r.sizeM2} m2` : null,
    /vista maravilhosa para a lagoa/i.test(r.text) ? 'lagoon view' : null,
    /térreo/i.test(r.text) ? 'ground floor' : null,
    r.maxGuests ? `up to ${r.maxGuests} guests` : null,
    r.beds,
    /amplo banheiro/i.test(r.text) ? 'large bathroom' : null,
  ].filter((x): x is string => !!x).join(', ');
}

export interface KsService { name: string; text: string; image: string | null }

/** /servicos: image widget + text widget (h4 name, paragraph) pairs. */
export function parseKsServices(servicesHtml: string): KsService[] {
  const out: KsService[] = [];
  let lastImg: string | null = null;
  for (const w of parse(servicesHtml).querySelectorAll('.cs-widget')) {
    if (w.classList.contains('cs-image-widget')) { lastImg = imgUrl(w.querySelector('img') ?? { getAttribute: () => undefined }); continue; }
    if (!w.classList.contains('cs-text-widget')) continue;
    const name = collapse(w.querySelector('h4')?.text ?? '');
    if (!name) continue;
    const text = w.querySelectorAll('p').map(p => collapse(p.text)).filter(Boolean).join(' ');
    out.push({ name, text, image: lastImg });
    lastImg = null;
  }
  return out;
}

/** Address line in the footer ("Av. Praia dos Nobres, 741 - Sao Tome, Praia Seca - Araruama - RJ, 28970-000"). */
export function ksAddress(html: string): string | null {
  const root = parse(html);
  for (const el of root.querySelectorAll('head, script, style')) el.remove();
  return root.structuredText.split('\n').map(l => collapse(l)).find(l => /Praia Seca - Araruama/i.test(l)) ?? null;
}

/** Amounts printed on /acomodacoes (none today); returned so fetchSlots can flag them. */
export function ksVisiblePrices(roomsHtml: string): string[] {
  return findPrices(textOf(roomsHtml)).map(p => p.raw);
}

export interface KsPages { home: string; rooms: string; services: string }

export function parseKiteSuitesContent(p: KsPages): OfferContent {
  const siteRooms = parseKsRooms(p.rooms);
  const services = parseKsServices(p.services);
  const homeLines = lines(p.home);
  const kite = services.find(s => /Kitesurf/i.test(s.name)) ?? null;
  const hasPool = homeLines.includes('PISCINA');
  const amenities = [...new Set(siteRooms.flatMap(r => r.amenities))];

  const rooms: ContentRoom[] = siteRooms.map(r => ({
    name: r.name,
    description: roomDescription(r) || null,
    features: r.amenities.filter(a => a !== 'Breakfast'),
  }));

  // the kite-lesson photo first, then the suites round-robin (first photo of each suite, then the second ...)
  const imageUrls: string[] = [];
  if (kite?.image) imageUrls.push(kite.image);
  const longest = Math.max(0, ...siteRooms.map(r => r.images.length));
  for (let i = 0; i < longest; i++) for (const r of siteRooms) if (r.images[i] && !imageUrls.includes(r.images[i])) imageUrls.push(r.images[i]);

  const n = siteRooms.length;
  const summary = [
    `Kite Suites is a small guesthouse with a restaurant at Praia Seca (Araruama, Rio de Janeiro state, Brazil), facing the Lagoa de Araruama, with ${n || 3} suites: ${siteRooms.map(r => r.name).join(', ')}.`,
    `The suites have air conditioning, a minibar and Wi-Fi, two of them with a lagoon view for up to 3 guests and one on the ground floor for up to 4; breakfast is included${hasPool ? ', and there is a pool' : ''}, beach service and a lagoon-front restaurant.`,
    kite ? 'Kite lessons are booked with the house\'s certified instructors; partners run buggy, jet ski and boat tours.' : '',
    'Stays and lessons are requested by WhatsApp; the site publishes no prices, so the listing is price on request.',
  ].filter(Boolean).join(' ');

  const address = ksAddress(p.home);
  return {
    kind: 'accommodation',
    title: 'Kite Suites',
    summary,
    continent: 'South America',
    country: 'Brazil',
    region: 'Araruama, Rio de Janeiro',
    spot: 'Praia Seca, Araruama',
    itinerarySpots: [],
    durationDays: null,
    skillLevels: [], // the site names no levels
    kiteLessons: kite ? /aula/i.test(kite.text) : null,
    equipmentRental: null,
    beginnerFriendly: null,
    includedServices: amenities,
    optionalServices: [
      kite ? 'Kite lessons with certified instructors (booked by WhatsApp, price on request)' : null,
      'Restaurant facing the lagoon (breakfast, lunch, açaí)',
      'Beach service',
      'Buggy, jet ski and boat tours in Praia Seca and Arraial do Cabo (partners)',
    ].filter((x): x is string => !!x),
    accommodation: 'lagoon-front guesthouse suites',
    mealPlan: amenities.includes('Breakfast') ? 'breakfast' : null,
    languages: ['pt'], // the site is Portuguese only
    rooms,
    imageUrls: imageUrls.slice(0, 12),
    heroVideoUrl: null,
    sourceUrl: KS_ROOMS_URL,
    bookingUrl: `https://wa.me/${WHATSAPP.slice(1)}`,
    sourceText: [
      `home: ${homeLines.join(' ')}`,
      `address: ${address ?? '-'}`,
      `rooms: ${siteRooms.map(r => `${r.name}: ${r.text} [${r.images.length} photos]`).join(' | ')}`,
      `services: ${services.map(s => `${s.name}: ${s.text}`).join(' | ')}`,
    ].join('\n'),
  };
}

// --- adapter ----------------------------------------------------------------------------------
export const kiteSuitesPraiaSeca: OfferAdapter = {
  key: 'kite-suites-praia-seca',
  name: 'Kite Suites Praia Seca',
  kind: 'accommodation',
  disciplines: ['kitesurf'], // no wing foil on the site
  operator: {
    name: 'Kite Suites',
    websiteUrl: SITE,
    rootDomain: 'kitesuites.com.br',
    whatsapp: WHATSAPP,
    phone: WHATSAPP,
  },
  url: KS_ROOMS_URL,
  slotMethod: 'price_table',
  instantBooking: false, // WhatsApp request only; liveAvailability unset
  fetchBudget: 4,
  confidence: 'low', // no prices on the site, request only
  async fetchContent() {
    const home = await page(KS_HOME_URL);
    const rooms = await page(KS_ROOMS_URL);
    const services = await page(KS_SERVICES_URL);
    return parseKiteSuitesContent({ home, rooms, services });
  },
  async fetchSlots(ctx): Promise<Slot[]> {
    const html = await page(KS_ROOMS_URL);
    if (parseKsRooms(html).length === 0) throw new Error('kite-suites: suite sections missing on /acomodacoes (layout changed?)');
    const prices = ksVisiblePrices(html);
    if (prices.length) ctx.note(`prices appeared on /acomodacoes (${prices.slice(0, 5).join(', ')}): extend the adapter`);
    return [];
  },
};
